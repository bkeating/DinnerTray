for(int i=0;i<60;i++)body.Step(1f/120,Array.Empty<Perch>(),bounds,0);
Check(Math.Abs(body.X-500)<.1 && Math.Abs(body.Y-350)<.1, "Projectile follows analytic gravity arc at apex");
for(int i=0;i<60;i++)body.Step(1f/120,Array.Empty<Perch>(),bounds,0);
Check(Math.Abs(body.X-800)<.1 && Math.Abs(body.Y-500)<.1, "Projectile retains horizontal momentum");
body.Drop(200,200);body.Launch(0,-300);body.Step(.01f,platforms,bounds,0);
Check(!body.Grounded && body.Y<200,"Launching upward must not stick to platform");
var gesture=new ThrowGesture();gesture.Add(new(0,0),0);gesture.Add(new(100,-50),.1);
Check(Math.Abs(gesture.Velocity().X-1000)<.1 && Math.Abs(gesture.Velocity().Y+500)<.1,"Fling estimates recent pointer velocity");
gesture.Add(new(100,-50),.5);Check(gesture.Velocity()==System.Drawing.PointF.Empty,"Holding before release cancels stale momentum");
gesture.Clear();gesture.Add(new(0,0),0);gesture.Add(new(10000,10000),.1);
var fling=gesture.Velocity();Check(Math.Abs(Math.Sqrt(fling.X*fling.X+fling.Y*fling.Y)-2400)<1,"Extreme pointer speeds are bounded");
var world=new SmashWorld();world.Reset(bounds);
for(int i=0;i<2400;i++)world.Step(1f/240);
Check(world.Broken==0 && world.Blocks.Count==10,"Stack remains stable without a projectile");
Check(world.Blocks.All(b=>b.Y+b.Rect.Height<=bounds.Bottom+.1),"Blocks do not sink below taskbar");
var target=world.Blocks[0];body.Drop(target.X-22,target.Y+45);body.Launch(1800,0);world.Hit(body);
Check(world.Broken>0,"Fast impact breaks a wooden block");
Check(body.VelocityX<1800,"Collision transfers momentum out of sheep");
Check(world.Chips.Count>0,"Broken blocks emit debris");
for(int i=0;i<300;i++)world.Step(1f/240);
world.Reset(bounds);Check(world.Broken==0 && world.Blocks.Count==10 && world.Chips.Count==0,"Reset restores clean pile");
Console.WriteLine($"PASS: {assertions-gameStart} throwing and block physics assertions");
