using DinnerTray;

int assertions = 0;
void Check(bool ok, string message) { if (!ok) throw new Exception(message); assertions++; }
var now = DateTimeOffset.UtcNow;
var healthy = new PlaybackHealth("a", true, false, false, 123, 600, 4, false, false, true, 0, false);
var error = healthy with { Time = 0, Ready = 0, Paused = true, RetryError = true };
var state = new PlaybackRecovery();
Check(state.Observe(healthy, now) == null, "Healthy playback must not refresh");
Check(state.Observe(error, now.AddSeconds(1)) == null, "Transient errors need a grace period");
var resume = state.Observe(error, now.AddSeconds(7));
Check(resume?.Time == 123 && resume.Paused == false, "Preserve last good position and intent, not failed player state");
Check(!state.CanRestore(error), "Do not restore while error still displayed");
Check(state.CanRestore(healthy), "Restore after player recovers");
Check(!state.CanRestore(healthy with { Ready = 1 }), "Metadata alone is not enough to seek and resume");
Check(!state.CanRestore(healthy with { Ready = 2 }), "Wait for playable future data before restoring");
Check(!state.CanRestore(healthy with { Ad = true }), "Do not seek or skip an ad");
Check(!state.CanRestore(healthy with { VideoId = "b" }), "Never seek a different video");
Check(state.Observe(error, now.AddSeconds(15)) == null, "Do not refresh during pending restore");
state.Restored();
state.Observe(error, now.AddSeconds(20));
Check(state.Observe(error, now.AddSeconds(26)) == null, "Do not refresh again immediately after a relapse");
Check(state.Observe(error, now.AddSeconds(68)) != null, "Permit one retry after the cooldown");
state.Restored();
state.Observe(error, now.AddSeconds(80));
Check(state.Observe(error, now.AddSeconds(150)) == null, "Cap retries to prevent loops");
Check(state.Observe(error, now.AddMinutes(11)) != null, "Retry budget eventually recovers");

foreach (var normal in new[] { healthy with { Paused = true }, healthy with { Ready = 1 }, healthy with { Ended = true }, healthy with { Ad = true }, healthy with { MediaError = 1 }, healthy with { MediaError = 4 } })
{
    var s = new PlaybackRecovery(); s.Observe(healthy, now);
    s.Observe(normal, now.AddSeconds(1));
    Check(s.Observe(normal, now.AddSeconds(60)) == null, "Pause, buffering, ending, ads and non-transient errors must not refresh");
}
var offline = new PlaybackRecovery(); offline.Observe(healthy, now);
offline.Observe(error with { Online = false }, now.AddSeconds(1));
Check(offline.Observe(error with { Online = false }, now.AddSeconds(60)) == null, "Do not refresh offline");
var fresh = new PlaybackRecovery(); fresh.Observe(error, now);
Check(fresh.Observe(error, now.AddSeconds(60)) == null, "Do not retry errors without prior playback");
var paused = new PlaybackRecovery(); paused.Observe(healthy with { Paused = true }, now);
paused.Observe(error, now.AddSeconds(1));
Check(paused.Observe(error, now.AddSeconds(7))?.Paused == true, "Preserve intentional pause across refresh");
paused.CancelResume(); Check(!paused.CanRestore(healthy), "Tray play/pause cancels pending resume");
var navigation = new PlaybackRecovery(); navigation.Observe(healthy, now);
navigation.Observe(error, now.AddSeconds(1));
Check(navigation.Observe(error with { VideoId = "b" }, now.AddSeconds(7)) == null, "Navigation must clear prior playback");
var decoder = new PlaybackRecovery(); decoder.Observe(healthy, now);
decoder.Observe(error with { RetryError = false, MediaError = 3 }, now.AddSeconds(1));
Check(decoder.Observe(error with { RetryError = false, MediaError = 3 }, now.AddSeconds(7)) != null, "Recover decoder errors");
Console.WriteLine($"PASS: {assertions} recovery assertions");
int physicsStart = assertions;
var bounds = new System.Drawing.Rectangle(0, 0, 1000, 800);
var platforms = new[] { new Perch(100, 300, 200), new Perch(0, 1000, 800) };
var body = new DesktopPhysics(); body.Drop(200, 0);
for (int i = 0; i < 60; i++) body.Step(.016f, platforms, bounds, 0);
Check(body.Grounded && body.Y == 200, "Fall lands on first crossed window top");
for (int i = 0; i < 300; i++) body.Step(.016f, platforms, bounds, 100);
Check(body.Grounded && body.Y == 800, "Walking off a window falls to the taskbar");
body.Drop(200, 200); body.Step(.016f, platforms, bounds, 0);
body.Step(.016f, new[] { platforms[1] }, bounds, 0);
Check(!body.Grounded && body.Y > 200, "Removing the supporting window starts a fall");
body.Drop(200, 250);
for (int i = 0; i < 100; i++) body.Step(.016f, platforms, bounds, 0);
Check(body.Y == 800, "A window above a falling sheep cannot catch it");
body.Drop(990, 800); body.Direction = 1;
body.Step(.016f, platforms, bounds, 100); body.Step(.016f, platforms, bounds, 100);
Check(body.Direction == -1 && body.X <= 976, "Turn around at monitor edge");
body.Drop(200, 190); body.VelocityY = 800; body.Step(.05f, platforms, bounds, 0);
Check(body.Y == 200 && body.Grounded, "Fast falls cannot tunnel through platforms");
body.Drop(-500, -200);
var negative = new System.Drawing.Rectangle(-1000, -300, 1000, 1000);
for(int i=0;i<100;i++) body.Step(.016f, new[] {new Perch(-1000, 0, 700)}, negative, 0);
Check(body.Y == 700 && body.Grounded, "Support monitors with negative coordinates");
Console.WriteLine($"PASS: {assertions - physicsStart} desktop physics assertions");
int gameStart = assertions;
